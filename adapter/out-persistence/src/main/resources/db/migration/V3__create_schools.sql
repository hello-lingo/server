create table schools (
	id     bigint generated by default as identity primary key,
	name   varchar(100) not null,
	hidden boolean default false not null,
	constraint uk_schools_name unique (name)
);

-- 같은 메일 도메인을 여러 캠퍼스(학교)가 함께 쓸 수 있으므로 도메인은 학교 안에서만 고유하다
create table school_domains (
	id        bigint generated by default as identity primary key,
	school_id bigint not null references schools (id),
	domain    varchar(253) not null,
	constraint uk_school_domains_school_domain unique (school_id, domain)
);

-- 이메일 인증에서 도메인으로 학교를 찾는다. 학교별 조회는 위 고유 제약(school_id가 앞 열)의 인덱스를 쓴다.
create index ix_school_domains_domain on school_domains (domain);
